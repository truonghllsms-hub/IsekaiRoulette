// Embed self-hosted fonts and decorations so the SVG export and offline bundle need no network.
const fs=require('fs'),path=require('path');
function buildChronicleAssets(){
  const root=path.join(__dirname,'..'),dir=path.join(root,'img/ui/chronicle');
  const data=(file,mime)=>`data:${mime};base64,${fs.readFileSync(path.join(dir,file)).toString('base64')}`;
  const fonts=[['Regular',400,'normal'],['Bold',700,'normal'],['Italic',400,'italic'],['BoldItalic',700,'italic']]
    .map(([file,weight,style])=>({weight,style,src:data(`NotoSerif-${file}.woff`,'font/woff')}));
  const assets={fonts,paper:data('paper.webp','image/webp'),badge:data('badge.webp','image/webp'),wax:data('wax.webp','image/webp')};
  const source='// Generated by tools/build-chronicle-assets.js; includes Noto Serif (OFL, see img/ui/chronicle/FONT-LICENSE.txt).\n(function(root){const assets='+JSON.stringify(assets)+';if(typeof module!=="undefined"&&module.exports)module.exports=assets;else root.ChronicleAssets=assets;})(typeof window!=="undefined"?window:globalThis);\n';
  fs.writeFileSync(path.join(root,'chronicle-assets.js'),source);
  console.log(`Chronicle assets: ${fonts.length} font faces, 3 decorations, ${Math.round(Buffer.byteLength(source)/1024)} KiB.`);
}
if(require.main===module)buildChronicleAssets();else module.exports=buildChronicleAssets;
