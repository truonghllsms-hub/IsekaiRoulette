// Bundles data/*.json into data.js so index.html works when opened straight from disk.
const fs = require("fs");
const path = require("path");
const { loadData } = require("./load");
const { validate } = require("./validate");

const data = loadData();
const errors = validate(data);
if (errors.length) {
  console.error(`Build dừng: ${errors.length} lỗi dữ liệu.`);
  for (const e of errors) console.error("  - " + e);
  process.exit(1);
}
for (const e of data.events) delete e._file;
const out = path.join(__dirname, "..", "data.js");
fs.writeFileSync(out, "// Generated by tools/build.js. Do not edit; edit data/*.json instead.\nwindow.GAME_DATA = " + JSON.stringify(data) + ";\n", "utf8");
console.log(`Đã build data.js: ${data.races.length} tộc, ${data.events.length} sự kiện, ${data.origins.length} xuất thân.`);
