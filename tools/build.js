// Bundles data/*.json into data.js so index.html works when opened straight from disk.
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { loadData } = require("./load");
const { validate } = require("./validate");

const data = loadData();
const errors = validate(data);
if (errors.length) {
  console.error(`Build dừng: ${errors.length} lỗi dữ liệu.`);
  for (const e of errors) console.error("  - " + e);
  process.exit(1);
}
for (const e of data.events) delete e._file;
// an event every race it was written for has stepped away from (a race pack replaced it) can never
// happen: it stays in data/ but not in the game file
const raceIds = data.races.map((r) => r.id);
const before = data.events.length;
data.events = data.events.filter((e) => raceIds.some((r) => (!e.races || e.races.includes(r)) && !(e.excludeRaces || []).includes(r)));
if (before > data.events.length) console.log(`Bỏ ${before - data.events.length} sự kiện không tộc nào gặp được.`);
// character sprites: one atlas per person (tools/import-sheets.py) with the frame of every column
const atlasFile = path.join(__dirname, "..", "img", "atlas.json");
data.sprites = fs.existsSync(atlasFile) ? JSON.parse(fs.readFileSync(atlasFile, "utf8")) : {};
data.spritePresentation = JSON.parse(fs.readFileSync(path.join(__dirname,"..","img/presentation.json"),"utf8"));
// A new pixel payload gets a new URL, including when the filename is stable.
for (const sprite of Object.values(data.sprites)) {
  const file = path.join(__dirname, "..", sprite._src);
  const hash=crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
  const person=Object.keys(data.sprites).find(k=>data.sprites[k]===sprite);
  if(data.spritePresentation.people[person]?.sha256!==hash)throw new Error(`Stale UI focus metadata: ${person}. Run python3 tools/build-presentation.py`);
  sprite._src += "?v=" + hash.slice(0,12);
}
// Illustrated Human portraits (artbook templates H01-H08, F01-F08): one image per look, each shown
// through the same sprite path as an atlas frame of its own ("pt/<template>/<look>")
require("./portraits").addPortraits(data);
const worldMap = "img/maps/aethelgard-01.png";
const mapHash = crypto.createHash("sha256").update(fs.readFileSync(path.join(__dirname,"..",worldMap))).digest("hex").slice(0,12);
data.worldMap = {src:worldMap+"?v="+mapHash,width:1536,height:1024,title:"Biên niên cổ đồ Aethelgard"};
const out = path.join(__dirname, "..", "data.js");
fs.writeFileSync(out, "// Generated by tools/build.js. Do not edit; edit data/*.json instead.\nwindow.GAME_DATA = " + JSON.stringify(data) + ";\n", "utf8");
console.log(`Đã build data.js: ${data.races.length} tộc, ${data.events.length} sự kiện, ${data.origins.length} xuất thân, ${Object.keys(data.sprites).filter((k) => !k.startsWith("pt/")).length} người có ảnh${data.portraits ? `, ${Object.keys(data.portraits.looks).length} mẫu chân dung minh họa` : ""}.`);
